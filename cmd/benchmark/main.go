// benchmark compiles, sets up and proves the hash, encryption and signature gadgets
// with Groth16 on BN254 and writes the results to BENCHMARKS.md.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"runtime"
	"runtime/debug"
	"slices"
	"strings"
	"time"

	"github.com/consensys/gnark-crypto/ecc"
	"github.com/consensys/gnark/backend/groth16"
	"github.com/consensys/gnark/constraint"
	"github.com/consensys/gnark/frontend"
	"github.com/consensys/gnark/frontend/cs/r1cs"
	"github.com/consensys/gnark/logger"
)

const batchSize = 10

var errNotVerified = errors.New("proof does not verify")

type measurement struct {
	constraints int
	bsb22       bool
	proveMs     float64
	err         error
}

type result struct {
	row    row
	single measurement
	batch  measurement
}

func main() {
	runs := flag.Int("runs", 5, "proofs per circuit; the median proving time is reported")
	out := flag.String("out", "BENCHMARKS.md", "output file, overwritten")
	only := flag.String("only", "", "measure only rows whose name contains this substring")
	withBatch := flag.Bool("x10", true, "also measure ten instances in one circuit")
	flag.Parse()
	if *runs < 1 {
		fail(fmt.Errorf("-runs must be at least 1"))
	}
	logger.Disable()

	start := time.Now()
	var results []result
	for _, r := range rows() {
		if !strings.Contains(r.name, *only) {
			continue
		}
		res := result{row: r, single: measureRow(r, 1, *runs)}
		if *withBatch {
			res.batch = measureRow(r, batchSize, *runs)
		} else {
			res.batch.err = errors.New("skipped with -x10=false")
		}
		results = append(results, res)
	}
	if len(results) == 0 {
		fail(fmt.Errorf("no row matches -only %q", *only))
	}
	if err := os.WriteFile(*out, []byte(render(results, *runs)), 0o644); err != nil {
		fail(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s in %s\n", *out, time.Since(start).Round(time.Second))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "benchmark:", err)
	os.Exit(1)
}

// measureRow measures one row at n instances. A proof that does not verify
// aborts the run; any other failure is recorded for the row's footnote.
func measureRow(r row, n, runs int) measurement {
	fmt.Fprintf(os.Stderr, "%s x%d: ", r.name, n)
	m := measure(r, n, runs)
	runtime.GC()
	debug.FreeOSMemory()
	if errors.Is(m.err, errNotVerified) {
		fmt.Fprintln(os.Stderr)
		fail(fmt.Errorf("%s x%d: %w", r.name, n, m.err))
	}
	if m.err != nil {
		fmt.Fprintf(os.Stderr, "failed: %v\n", m.err)
		return m
	}
	fmt.Fprintf(os.Stderr, "%s constraints, BSB22 %s, prove %.1f ms\n", thousands(m.constraints), yesNo(m.bsb22), m.proveMs)
	return m
}

func measure(r row, n, runs int) measurement {
	var m measurement
	circuit, assignment, err := r.circuits(n)
	if err != nil {
		m.err = err
		return m
	}
	field := ecc.BN254.ScalarField()
	ccs, err := frontend.Compile(field, r1cs.NewBuilder, circuit)
	if err != nil {
		m.err = fmt.Errorf("compile: %w", err)
		return m
	}
	m.constraints = ccs.GetNbConstraints()
	if commitments, ok := ccs.GetCommitments().(constraint.Groth16Commitments); ok {
		m.bsb22 = len(commitments) > 0
	}
	pk, vk, err := groth16.Setup(ccs)
	if err != nil {
		m.err = fmt.Errorf("setup: %w", err)
		return m
	}
	durations := make([]time.Duration, runs)
	for k := range durations {
		witness, err := frontend.NewWitness(assignment, field)
		if err != nil {
			m.err = fmt.Errorf("witness: %w", err)
			return m
		}
		started := time.Now()
		proof, err := groth16.Prove(ccs, pk, witness)
		durations[k] = time.Since(started)
		if err != nil {
			m.err = fmt.Errorf("prove: %w", err)
			return m
		}
		if k == 0 {
			public, err := witness.Public()
			if err != nil {
				m.err = fmt.Errorf("public witness: %w", err)
				return m
			}
			if err := groth16.Verify(proof, vk, public); err != nil {
				m.err = fmt.Errorf("%w: %v", errNotVerified, err)
				return m
			}
		}
	}
	slices.Sort(durations)
	median := durations[len(durations)/2]
	if len(durations)%2 == 0 {
		median = (durations[len(durations)/2-1] + median) / 2
	}
	m.proveMs = float64(median.Microseconds()) / 1000
	return m
}

func render(results []result, runs int) string {
	var b strings.Builder
	b.WriteString(`# Gnark circuit benchmarks

Generated by ` + "`go run ./cmd/benchmark`" + `, which overwrites this file.
Every circuit is compiled to BN254 R1CS and proven with Groth16.
Proving time is ` + "`groth16.Prove`" + ` alone, the median of ` + fmt.Sprint(runs) + ` runs; compilation,
setup and witness construction are excluded, and one proof per circuit is
verified. x10 is ten independent instances with distinct inputs in one
circuit, so the lookup variants share one table and one BSB22 commitment.
Hash inputs are private and each hash instance exposes its digest bytes.
X25519 rows take private scalar and peer bytes and expose the shared secret
bytes (ECDH) or the six packed key-agreement outputs (AgreeKey).
AES-256-CTR rows take a private 32-byte key and private plaintext bytes and
expose the 12-byte nonce and the ciphertext bytes. ECIES envelope rows add
X25519 key agreement, the Poseidon transcript and Zolana's key schedule, and expose
the packed recipient and ephemeral keys and the ciphertext bytes.
Ed25519 rows expose the original public-key and message bytes and keep the
signature private; SHA-512 of R || public key || message is in the circuit.

`)
	fmt.Fprintf(&b, "## %s — %s — %s — gnark %s\n", time.Now().UTC().Format("2006-01-02 15:04 UTC"), gitRevision(), cpuModel(), gnarkVersion())
	var notes []string
	cell := func(m measurement, value string) string {
		if m.err == nil {
			return value
		}
		notes = append(notes, m.err.Error())
		return fmt.Sprintf("—[^%d]", len(notes))
	}
	for _, section := range []string{sectionHasher, sectionX25519, sectionEd25519, sectionEncryption} {
		header := false
		for _, res := range results {
			if res.row.section != section {
				continue
			}
			if !header {
				fmt.Fprintf(&b, "\n### %s\n\n", section)
				b.WriteString("| Circuit | BSB22 | Constraints x1 | Proving x1 (ms) | Constraints x10 | Proving x10 (ms) |\n")
				b.WriteString("|---|---|---:|---:|---:|---:|\n")
				header = true
			}
			bsb22 := res.single
			if bsb22.err != nil {
				bsb22 = res.batch
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", res.row.name,
				cell(bsb22, yesNo(bsb22.bsb22)),
				cell(res.single, thousands(res.single.constraints)), cell(res.single, fmt.Sprintf("%.1f", res.single.proveMs)),
				cell(res.batch, thousands(res.batch.constraints)), cell(res.batch, fmt.Sprintf("%.1f", res.batch.proveMs)))
		}
	}
	if len(notes) > 0 {
		b.WriteString("\n")
		for i, note := range notes {
			fmt.Fprintf(&b, "[^%d]: %s\n", i+1, note)
		}
	}
	return b.String()
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

func thousands(n int) string {
	s := fmt.Sprint(n)
	var b strings.Builder
	for i, c := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			b.WriteByte(',')
		}
		b.WriteRune(c)
	}
	return b.String()
}

func command(name string, args ...string) string {
	out, err := exec.Command(name, args...).Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

func gitRevision() string {
	rev := command("git", "rev-parse", "--short", "HEAD")
	if rev == "" {
		return "unknown revision"
	}
	if command("git", "status", "--porcelain") != "" {
		rev += "+dirty"
	}
	return rev
}

func cpuModel() string {
	if runtime.GOOS == "darwin" {
		if model := command("sysctl", "-n", "machdep.cpu.brand_string"); model != "" {
			return model
		}
	}
	if info, err := os.ReadFile("/proc/cpuinfo"); err == nil {
		for _, line := range strings.Split(string(info), "\n") {
			if name, value, ok := strings.Cut(line, ":"); ok && strings.TrimSpace(name) == "model name" {
				return strings.TrimSpace(value)
			}
		}
	}
	return fmt.Sprintf("%s/%s, %d CPUs", runtime.GOOS, runtime.GOARCH, runtime.NumCPU())
}

func gnarkVersion() string {
	if info, ok := debug.ReadBuildInfo(); ok {
		for _, dep := range info.Deps {
			if dep.Path == "github.com/consensys/gnark" {
				return dep.Version
			}
		}
	}
	return "unknown"
}
